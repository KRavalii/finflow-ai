import { fetchProfiles } from './api/profiles'
import { act, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import App from './App'
import { createTransaction, deleteTransaction, fetchTransactions, updateTransaction } from './api/transactions'
import { records } from './test/fixtures'
import { askAssistant, fetchSummary } from './api/financial'
import { summaryFixture } from './test/financialFixtures'

vi.mock('./api/transactions', () => ({ fetchTransactions: vi.fn(), createTransaction: vi.fn(), updateTransaction: vi.fn(), deleteTransaction: vi.fn(), errorMessage: () => 'Unable to reach the backend.' }))
vi.mock('./components/Charts', () => ({ default: () => <div>Analytics chart region</div> }))
vi.mock('./api/profiles', () => ({ fetchProfiles: vi.fn(), createProfile: vi.fn(), updateProfile: vi.fn() }))
vi.mock('./api/financial', () => ({ fetchSummary: vi.fn(), askAssistant: vi.fn(), financialError: () => 'Unable to reach the backend.' }))

beforeEach(() => {
  vi.clearAllMocks()
  vi.mocked(fetchProfiles).mockResolvedValue([{ id: 1, name: 'My Profile', is_default: true, created_at: '2026-11-13', archived_at: null }])
  localStorage.clear()
  vi.mocked(fetchSummary).mockResolvedValue(summaryFixture)
  window.history.replaceState({}, '', '/')
  vi.mocked(fetchTransactions).mockResolvedValue(records)
  vi.mocked(createTransaction).mockResolvedValue({} as never)
  vi.mocked(updateTransaction).mockResolvedValue({} as never)
  vi.mocked(deleteTransaction).mockResolvedValue({} as never)
})

describe('financial workspace', () => {
  it('submits the reported Salary income case with INR and the original amount', async () => {
    window.history.replaceState({},'', '/transactions')
    render(<App />)
    await screen.findByText('Groceries')
    await userEvent.click(screen.getByRole('button',{name:'Add transaction'}))
    const dialog=within(screen.getByRole('dialog'))
    await userEvent.click(dialog.getByRole('button',{name:/Income/}))
    await userEvent.type(dialog.getByLabelText('Description'),'Salary')
    await userEvent.selectOptions(dialog.getByLabelText('Original currency'),'INR')
    await userEvent.type(dialog.getByLabelText('Amount (INR)'),'300')
    await userEvent.type(dialog.getByLabelText('Category'),'Salary')
    await userEvent.click(dialog.getByRole('button',{name:'Add transaction'}))
    await waitFor(()=>expect(createTransaction).toHaveBeenCalledWith(expect.objectContaining({description:'Salary',currency:'INR',amount:'300',category:'Salary',transaction_type:'income'})))
  })
  it('shares the reporting currency and policy between dashboard and assistant', async () => {
    render(<App />)
    await screen.findByText('$872.55')
    const inrSummary = { ...summaryFixture, currency: 'INR' as const, income: '80008.00', expenses: '10204.00', net_balance: '69804.00' }
    vi.mocked(fetchSummary).mockResolvedValue(inrSummary)
    vi.mocked(askAssistant).mockResolvedValue({ provider: 'rule_based', status: 'answered', intent: 'summary', summary: inrSummary, message: 'Financial summary (INR). Net balance: ₹69,804.00.' })
    await userEvent.selectOptions(screen.getByRole('combobox', { name: 'Reporting currency' }), 'INR')
    expect(await screen.findByText('₹69,804.00')).toBeInTheDocument()
    expect(localStorage.getItem('finflow.currency')).toBe('INR')
    expect(fetchTransactions).toHaveBeenLastCalledWith(expect.any(AbortSignal), { reporting_currency: 'INR', rate_policy: 'historical', profile_id: 1 })
    expect(fetchSummary).toHaveBeenLastCalledWith({ reporting_currency: 'INR', profile_id: 1 }, expect.any(AbortSignal))
    await userEvent.click(screen.getByRole('link', { name: 'AI Assistant' }))
    await screen.findByText('Your financial assistant.')
    await userEvent.click(screen.getByRole('button', { name: 'Summarize my finances' }))
    await userEvent.click(screen.getByRole('button', { name: 'Ask assistant' }))
    await waitFor(() => expect(askAssistant).toHaveBeenCalledWith('Summarize my finances', { reporting_currency: 'INR', profile_id: 1 }, expect.any(AbortSignal)))
    expect(await screen.findByText('Financial summary (INR). Net balance: ₹69,804.00.')).toBeInTheDocument()
  })
  it('does not relabel stale USD totals as another currency when rates fail', async () => {
    render(<App />)
    await screen.findByText('$872.55')
    vi.mocked(fetchSummary).mockRejectedValue(new Error('rates missing'))
    await userEvent.selectOptions(screen.getByRole('combobox', { name: 'Reporting currency' }), 'AED')
    expect(await screen.findByRole('alert')).toHaveTextContent('Unable to reach the backend')
    expect(screen.queryByText('$872.55')).not.toBeInTheDocument()
    expect(screen.queryByText(/AED.*872.55/)).not.toBeInTheDocument()
  })
  it('restores preferences and hides totals if any required converted amount is missing', async () => {
    localStorage.setItem('finflow.currency', 'INR')
    window.history.replaceState({}, '', '/transactions')
    render(<App />)
    await screen.findByText('Groceries')
    expect(screen.getByRole('combobox', { name: 'Reporting currency' })).toHaveValue('INR')
    expect(screen.getByText('Unavailable: missing exchange rates')).toBeInTheDocument()
  })
  it('submits the original amount in the explicitly selected transaction currency', async () => {
    window.history.replaceState({}, '', '/transactions')
    render(<App />)
    await screen.findByText('Groceries')
    await userEvent.click(screen.getByRole('button', { name: 'Add transaction' }))
    const dialog = within(screen.getByRole('dialog'))
    await userEvent.selectOptions(dialog.getByLabelText('Original currency'), 'AED')
    await userEvent.type(dialog.getByLabelText('Description'), 'Original purchase')
    await userEvent.type(dialog.getByLabelText('Amount (AED)'), '12.34')
    await userEvent.type(dialog.getByLabelText('Category'), 'Travel')
    await userEvent.click(dialog.getByRole('button', { name: 'Add transaction' }))
    await waitFor(() => expect(createTransaction).toHaveBeenCalledWith(expect.objectContaining({ currency: 'AED', amount: '12.34' })))
  })
  it('edits the original INR value rather than its USD reporting equivalent', async () => {
    window.history.replaceState({}, '', '/transactions')
    vi.mocked(fetchTransactions).mockResolvedValue([{ ...records[0], currency: 'INR', amount: '8000.00', converted_amount: '100.00', reporting_currency: 'USD' }])
    render(<App />)
    await screen.findByText('Paycheck')
    await userEvent.click(screen.getByRole('button', { name: 'Edit Paycheck' }))
    const dialog = within(screen.getByRole('dialog'))
    expect(dialog.getByLabelText('Original currency')).toHaveValue('INR')
    expect(dialog.getByLabelText('Amount (INR)')).toHaveValue('8000.00')
    await userEvent.click(dialog.getByRole('button', { name: 'Save changes' }))
    await waitFor(() => expect(updateTransaction).toHaveBeenCalledWith(1, expect.objectContaining({ currency: 'INR', amount: '8000.00' })))
  })
  it('loads real API totals and recent transactions', async () => {
    render(<App />)
    expect(await screen.findByText('$872.55')).toBeInTheDocument()
    expect(screen.getByText('$1,000.10')).toBeInTheDocument()
    expect(screen.getByText('$127.55')).toBeInTheDocument()
    expect(screen.getByText('Groceries')).toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'AI Assistant' })).toHaveAttribute('href', '/assistant')
  })
  it('shows loading rather than fabricated financial values', async () => {
    let finish!: (value: typeof records) => void
    vi.mocked(fetchTransactions).mockReturnValue(new Promise(resolve => { finish = resolve }))
    render(<App />)
    await waitFor(() => expect(screen.getByRole('status')).toHaveTextContent('Loading all your transactions'))
    expect(screen.queryByText('$0.00')).not.toBeInTheDocument()
    await act(async () => finish([]))
    expect(await screen.findByText('Your next chapter starts here')).toBeInTheDocument()
  })
  it('recovers from an API failure with retry', async () => {
    vi.mocked(fetchTransactions).mockRejectedValueOnce(new Error('offline'))
    render(<App />)
    expect(await screen.findByRole('alert')).toHaveTextContent('Unable to reach the backend')
    await userEvent.click(screen.getByRole('button', { name: 'Try again' }))
    expect(await screen.findByText('$872.55')).toBeInTheDocument()
  })
  it('navigates and filters transactions', async () => {
    render(<App />)
    await screen.findByText('Groceries')
    await userEvent.click(screen.getByRole('link', { name: 'Transactions' }))
    await userEvent.type(screen.getByRole('textbox', { name: 'Search transactions' }), 'Bus')
    expect(screen.getByText('Bus ticket')).toBeInTheDocument()
    expect(screen.queryByText('Groceries')).not.toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Clear filters' }))
    expect(screen.getByText('Groceries')).toBeInTheDocument()
  })
  it('creates a transaction using validated string amounts', async () => {
    render(<App />)
    await screen.findByText('Groceries')
    await userEvent.click(screen.getByRole('button', { name: 'Add transaction' }))
    const dialog = within(screen.getByRole('dialog'))
    await userEvent.type(dialog.getByLabelText('Description'), 'Lunch')
    await userEvent.type(dialog.getByLabelText('Amount (USD)'), '12.50')
    await userEvent.type(dialog.getByLabelText('Category'), 'Food')
    await userEvent.click(dialog.getByRole('button', { name: 'Add transaction' }))
    await waitFor(() => expect(createTransaction).toHaveBeenCalledWith(expect.objectContaining({ description: 'Lunch', amount: '12.50', transaction_type: 'expense' })))
    expect(await screen.findByText('Transaction added successfully.')).toBeInTheDocument()
  })
  it('edits complete records and requires confirmation before deletion', async () => {
    window.history.replaceState({}, '', '/transactions')
    render(<App />)
    await screen.findByText('Groceries')
    await userEvent.click(screen.getByRole('button', { name: 'Edit Groceries' }))
    let dialog = within(screen.getByRole('dialog'))
    await userEvent.clear(dialog.getByLabelText('Amount (USD)'))
    await userEvent.type(dialog.getByLabelText('Amount (USD)'), '100.00')
    await userEvent.click(dialog.getByRole('button', { name: 'Save changes' }))
    await waitFor(() => expect(updateTransaction).toHaveBeenCalledWith(2, expect.objectContaining({ amount: '100.00', category: 'Food', transaction_date: '2026-10-02' })))
    await screen.findByText('Transaction updated successfully.')
    await userEvent.click(screen.getByRole('button', { name: 'Delete Groceries' }))
    expect(deleteTransaction).not.toHaveBeenCalled()
    dialog = within(screen.getByRole('dialog'))
    await userEvent.click(dialog.getByRole('button', { name: 'Keep transaction' }))
    expect(deleteTransaction).not.toHaveBeenCalled()
    await userEvent.click(screen.getByRole('button', { name: 'Delete Groceries' }))
    await userEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Delete transaction' }))
    await waitFor(() => expect(deleteTransaction).toHaveBeenCalledWith(2, 1))
  })
  it('keeps failed forms open and displays the error', async () => {
    vi.mocked(createTransaction).mockRejectedValueOnce(new Error('offline'))
    render(<App />)
    await screen.findByText('Groceries')
    await userEvent.click(screen.getByRole('button', { name: 'Add transaction' }))
    const dialog = within(screen.getByRole('dialog'))
    await userEvent.type(dialog.getByLabelText('Description'), 'Lunch')
    await userEvent.type(dialog.getByLabelText('Amount (USD)'), '12.50')
    await userEvent.type(dialog.getByLabelText('Category'), 'Food')
    await userEvent.click(dialog.getByRole('button', { name: 'Add transaction' }))
    expect(await dialog.findByRole('alert')).toHaveTextContent('Unable to reach the backend')
    expect(dialog.getByLabelText('Description')).toHaveValue('Lunch')
  })
  it('paginates the filtered dataset', async () => {
    window.history.replaceState({}, '', '/transactions')
    vi.mocked(fetchTransactions).mockResolvedValue(Array.from({ length: 11 }, (_, index) => ({ ...records[0], id: index + 1, description: `Item ${index + 1}` })))
    render(<App />)
    await screen.findByText('Item 11')
    expect(screen.queryByText('Item 1')).not.toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Next page' }))
    expect(screen.getByText('Item 1')).toBeInTheDocument()
    expect(screen.queryByText('Item 11')).not.toBeInTheDocument()
  })
})
